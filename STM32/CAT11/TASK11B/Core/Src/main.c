int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  esp_send("AT\r\n", 300);
  esp_send("AT+CIPMUX=1\r\n", 400);
  esp_send("AT+CIPSERVER=1,80\r\n", 500);
  /* USER CODE END 2 */

  while (1)
  {
    /* USER CODE BEGIN 3 */
    uint8_t rx[256] = {0};
    if (HAL_UART_Receive(&huart1, rx, sizeof(rx) - 1, 200) == HAL_OK || strlen((char *)rx) > 0) {
      char *ipd = strstr((char *)rx, "+IPD,");
      if (ipd != NULL) {
        int link_id = atoi(ipd + 5);
        char json_body[96];
        char response[256];
        char cmd[48];
        snprintf(json_body, sizeof(json_body),
            "{\"node\":\"STM32_BluePill\",\"uptime_ms\":%lu}", (unsigned long)HAL_GetTick());
        int resp_len = snprintf(response, sizeof(response),
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: %d\r\n\r\n%s",
            (int)strlen(json_body), json_body);
        snprintf(cmd, sizeof(cmd), "AT+CIPSEND=%d,%d\r\n", link_id, resp_len);
        esp_send(cmd, 150);
        esp_send(response, 300);
        snprintf(cmd, sizeof(cmd), "AT+CIPCLOSE=%d\r\n", link_id);
        esp_send(cmd, 150);
      }
    }
    /* USER CODE END 3 */
  }
}

