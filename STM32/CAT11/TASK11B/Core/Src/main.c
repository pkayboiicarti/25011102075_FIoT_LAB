static void esp_send(const char *s, uint32_t wait_ms)
{
  uint8_t dump[128];
  HAL_UART_Transmit(&huart1, (uint8_t *)s, (uint16_t)strlen(s), 500);
  HAL_UART_Receive(&huart1, dump, sizeof(dump), wait_ms);
}
